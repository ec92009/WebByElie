const supportedLanguages = Object.keys(translations);
const root = document.documentElement;
const languageButtons = [...document.querySelectorAll(".language-button")];
const languageCards = [...document.querySelectorAll(".language-card")];
const languageGate = document.querySelector("#language-gate");
const menuContent = document.querySelector("#menu-content");
const headerLanguageSwitcher = document.querySelector("#header-language-switcher");
const skipLink = document.querySelector(".skip-link");

const getCopy = (language, path) => path.split(".").reduce((value, key) => value?.[key], translations[language]);

const setAttributeCopy = (element, descriptor, language) => {
  const separator = descriptor.indexOf(":");
  if (separator < 1) return;
  const attribute = descriptor.slice(0, separator);
  const path = descriptor.slice(separator + 1);
  const value = getCopy(language, path);
  if (typeof value === "string") element.setAttribute(attribute, value);
};

const applyLanguage = (language, updateUrl = true) => {
  const selectedLanguage = supportedLanguages.includes(language) ? language : null;
  const displayLanguage = selectedLanguage ?? "en";
  const text = translations[displayLanguage];
  const isMenuVisible = Boolean(selectedLanguage);
  root.lang = selectedLanguage ?? "en";
  document.title = isMenuVisible ? text.meta.title : text.meta.gateTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", isMenuVisible ? text.meta.description : text.meta.gateDescription);
  if (languageGate) languageGate.hidden = isMenuVisible;
  if (menuContent) menuContent.hidden = !isMenuVisible;
  if (headerLanguageSwitcher) headerLanguageSwitcher.hidden = !isMenuVisible;

  document.querySelectorAll("[data-copy]").forEach((element) => {
    const value = getCopy(displayLanguage, element.dataset.copy);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-copy-alt]").forEach((element) => {
    const value = getCopy(displayLanguage, element.dataset.copyAlt);
    if (typeof value === "string") element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-copy-attr]").forEach((element) => {
    setAttributeCopy(element, element.dataset.copyAttr, displayLanguage);
  });

  if (skipLink) {
    skipLink.setAttribute("href", isMenuVisible ? "#menu" : "#language-gate");
    skipLink.textContent = isMenuVisible ? text.accessibility.skip : text.accessibility.skipGate;
  }

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === selectedLanguage));
  });

  if (updateUrl) {
    const url = new URL(window.location.href);
    if (selectedLanguage) url.searchParams.set("lang", selectedLanguage);
    else url.searchParams.delete("lang");
    window.history.replaceState({}, "", url);
  }
};

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

languageCards.forEach((card) => {
  card.addEventListener("click", () => applyLanguage(card.dataset.lang));
});

const initialLanguage = new URLSearchParams(window.location.search).get("lang");
applyLanguage(initialLanguage, false);
